function applyStyle(text, styleMap) {
  return text.split("").map(char => {
    
    if (!/[a-zA-Z]/.test(char)) return char;

    const isUpperCase = char === char.toUpperCase();
    const lowerChar = char.toLowerCase();
    const mappedLower = styleMap[lowerChar];

    if (!mappedLower) return char;

    if (isUpperCase) {
      
      if (mappedLower.includes('̶')) {
        return char + '̶'; 
      }

      
      const codePoint = mappedLower.codePointAt(0);

      
      if (codePoint >= 0x1D41A && codePoint <= 0x1D7CB) {
        
        return String.fromCodePoint(codePoint - 26);
      } else if (codePoint >= 0x24B6 && codePoint <= 0x24CF) {
        
        return String.fromCodePoint(codePoint - 26);
      } else if (codePoint >= 0x1F130 && codePoint <= 0x1F14F) {
        
        return String.fromCodePoint(codePoint - 26);
      }

      
      return mappedLower.toUpperCase();
    }

    return mappedLower;
  }).join("");
}

